const config = new URL("./deno.json", import.meta.url);
const decoder = new TextDecoder();

async function existing(file: string): Promise<string | undefined> {
  try {
    return await Deno.readTextFile(file);
  } catch (error) {
    if (error instanceof Deno.errors.NotFound) return undefined;
    throw error;
  }
}

/** Deployment artifact for StepCage; the running service never bundles app code. */
export async function bundleStep(
  file: string,
  options: { check?: boolean } = {},
): Promise<string> {
  const path = await Deno.realPath(file);
  const source = new URL("file:///");
  source.pathname = path;
  const directory = await Deno.makeTempDir({ prefix: "mecha-step-build-" });
  let bundle: string;
  try {
    const entry = `${directory}/entry.ts`;
    await Deno.writeTextFile(
      entry,
      `import { step } from ${JSON.stringify(source.href)};
export const reads = [];
export const queries = {};
export const plan = (host, _seed, state) => step(host, state);
export const finish = () => ({});
`,
    );
    const result = await new Deno.Command(Deno.execPath(), {
      args: [
        "bundle",
        "--config",
        decodeURIComponent(config.pathname),
        "--frozen",
        "--platform",
        "browser",
        "--format",
        "esm",
        "--minify",
        entry,
      ],
      stdout: "piped",
      stderr: "piped",
    }).output();
    if (!result.success) {
      throw new Error(
        `step bundle ${file} failed (${result.code}):\n${
          decoder.decode(result.stderr)
        }`,
      );
    }
    bundle = `// Generated by step-build.ts from ${
      source.pathname.split("/").at(-1)
    }; do not edit.\n${decoder.decode(result.stdout)}`;
  } finally {
    await Deno.remove(directory, { recursive: true });
  }
  const output = `${file}.bundle.js`;
  const previous = await existing(output);
  if (options.check) {
    if (previous !== bundle) throw new Error(`stale step bundle: ${output}`);
  } else if (previous !== bundle) {
    await Deno.writeTextFile(output, bundle);
  }
  return bundle;
}

if (import.meta.main) {
  const check = Deno.args.includes("--check");
  const files = Deno.args.filter((arg) => arg !== "--check");
  if (!files.length || files.some((file) => file.startsWith("--"))) {
    throw new Error("usage: step-build.ts [--check] <step.ts>...");
  }
  for (const file of files) await bundleStep(file, { check });
}
