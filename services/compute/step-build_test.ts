import { assertEquals, assertRejects, assertStringIncludes } from "@std/assert";
import { bundleStep } from "./step-build.ts";
import { StepCage } from "./step-cage.ts";

Deno.test("step bundle includes local TypeScript dependencies and preserves unchanged artifacts", async () => {
  const directory = await Deno.makeTempDir();
  try {
    const file = `${directory}/authored.ts`;
    await Deno.writeTextFile(
      `${directory}/helper.ts`,
      "export const value: number = 3;",
    );
    await Deno.writeTextFile(
      file,
      `import {value} from './helper.ts';
      export const step = (_host: unknown, state: number) => ({checkpoint: state + value, writes: {}, done: true});`,
    );
    const source = await bundleStep(file);
    assertStringIncludes(source, "Generated by step-build.ts from authored.ts");
    const artifact = `${file}.bundle.js`;
    const timestamp = new Date("2000-01-01T00:00:00Z");
    await Deno.utime(artifact, timestamp, timestamp);
    assertEquals(await bundleStep(file), source);
    assertEquals((await Deno.stat(artifact)).mtime, timestamp);
    assertEquals(await bundleStep(file, { check: true }), source);
    using cage = new StepCage({ file, source, endowments: [] });
    const unused = () => Promise.reject(new Error("unexpected host call"));
    assertEquals(
      await cage.advance({
        seed: 0,
        query: unused,
        wasm: unused,
        wasmFromQuery: unused,
      }, 4),
      {
        checkpoint: 7,
        writes: {},
        done: true,
      },
    );
    await Deno.writeTextFile(
      `${directory}/helper.ts`,
      "export const value: number = 9;",
    );
    await assertRejects(
      () => bundleStep(file, { check: true }),
      Error,
      "stale step bundle",
    );
    assertEquals(await Deno.readTextFile(artifact), source);
    const updated = await bundleStep(file);
    assertEquals(updated === source, false);
    assertEquals(await bundleStep(file, { check: true }), updated);
  } finally {
    await Deno.remove(directory, { recursive: true });
  }
});

Deno.test("step bundle rejects absent artifacts in check mode and missing step exports", async () => {
  const directory = await Deno.makeTempDir();
  try {
    const file = `${directory}/authored.ts`;
    await Deno.writeTextFile(
      file,
      "export const step = () => ({checkpoint: null, writes: {}, done: true});",
    );
    await assertRejects(
      () => bundleStep(file, { check: true }),
      Error,
      "stale step bundle",
    );
    await Deno.writeTextFile(file, "export const other = 1;");
    await assertRejects(() => bundleStep(file), Error, "step bundle");
    await assertRejects(
      () => Deno.stat(`${file}.bundle.js`),
      Deno.errors.NotFound,
    );
  } finally {
    await Deno.remove(directory, { recursive: true });
  }
});
